"""Generate the embedded matplotlib colormap registry.

matplotlib is a development-only tool here: the generated Rust and Python
tables make the built wheel independent of it. Run after upgrading matplotlib:

    python tools/generate_colormaps.py

Every registered base colormap is sampled at its own LUT resolution, and the
`_r` variants are derived by reversing the lookup index in both consumers.
"""

import pathlib

import matplotlib
import numpy as np
from matplotlib.colors import ListedColormap, to_rgba

ROOT = pathlib.Path(__file__).resolve().parents[1]


def bright(value):
    """Convert one matplotlib colour to an 8-bit RGB triple."""
    return tuple(int(round(float(channel) * 255.0)) for channel in to_rgba(value)[:3])


def table(name):
    cmap = matplotlib.colormaps[name]
    if isinstance(cmap, ListedColormap):
        entries = [to_rgba(colour) for colour in cmap.colors]
    else:
        entries = [to_rgba(colour) for colour in cmap(np.linspace(0.0, 1.0, cmap.N))]
    return [bright(colour) for colour in entries]


def names():
    return sorted(name for name in matplotlib.colormaps if not name.endswith("_r"))


def write_python(registry):
    lines = [
        '"""Generated by tools/generate_colormaps.py; do not edit."""',
        "",
        f"# matplotlib {matplotlib.__version__}",
        "COLORMAPS = {",
    ]
    for name in names():
        lines.append(f'    "{name}": (')
        entries = registry[name]
        for start in range(0, len(entries), 6):
            chunk = ", ".join(repr(colour) for colour in entries[start:start + 6])
            lines.append(f"        {chunk},")
        lines.append("    ),")
    lines.append("}")
    lines.append("")
    path = ROOT / "python" / "matplotvite" / "_cmaps.py"
    path.write_text("\n".join(lines))


def write_rust(registry):
    lines = [
        "// Generated by tools/generate_colormaps.py; do not edit.",
        f"// matplotlib {matplotlib.__version__}",
        "",
        "pub(crate) struct CmapDef {",
        "    pub(crate) name: &'static str,",
        "    pub(crate) colors: &'static [[u8; 3]],",
        "}",
        "",
        "pub(crate) static CMAPS: &[CmapDef] = &[",
    ]
    for name in names():
        lines.append("    CmapDef {")
        lines.append(f'        name: "{name}",')
        lines.append("        colors: &[")
        entries = registry[name]
        for start in range(0, len(entries), 6):
            chunk = ", ".join(f"[{r}, {g}, {b}]" for r, g, b in entries[start:start + 6])
            lines.append(f"            {chunk},")
        lines.append("        ],")
        lines.append("    },")
    lines.append("];")
    lines.append("")
    lines.append("/// Exact registry lookup first, then a case-insensitive fallback.")
    lines.append("pub(crate) fn lookup(name: &str) -> Option<&'static CmapDef> {")
    lines.append("    let index = match name {")
    for index, name in enumerate(names()):
        lines.append(f'        "{name}" => Some({index}usize),')
    lines.append("        _ => None,")
    lines.append("    };")
    lines.append("    let index = index")
    lines.append("        .or_else(|| CMAPS.iter().position(|c| c.name.eq_ignore_ascii_case(name)))?;")
    lines.append("    CMAPS.get(index)")
    lines.append("}")
    lines.append("")
    path = ROOT / "src" / "cmap_data.rs"
    path.write_text("\n".join(lines))


def main():
    registry = {name: table(name) for name in names()}
    write_python(registry)
    write_rust(registry)
    total = sum(len(colours) for colours in registry.values())
    print(
        f"wrote {len(registry)} base colormaps ({len(registry) * 2} names, "
        f"{total} colours) from matplotlib {matplotlib.__version__}"
    )


if __name__ == "__main__":
    main()
